import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage();
await p.goto('https://raw.githack.com/azharshahim/Scanpro-ai/main/index.html', { waitUntil: 'load', timeout: 60000 });
await p.waitForTimeout(1500);
const html = await p.evaluate(() => document.documentElement.outerHTML);
console.log('len', html.length);
console.log('--- début ---\n' + html.slice(0, 700));
console.log('--- fin ---\n' + html.slice(-900));
console.log('iframes:', await p.evaluate(() => Array.from(document.querySelectorAll('iframe')).map(f => f.src)));
await b.close();
